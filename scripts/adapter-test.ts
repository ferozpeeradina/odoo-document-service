import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { OdooDocumentService } from '../adapter/OdooDocumentService.ts';
const f = JSON.parse(await fs.readFile('runtime/accounts.json', 'utf8'));
const j = JSON.parse(await fs.readFile('runtime/journey.json', 'utf8'));
const base = 'http://127.0.0.1:18069';
const auth = await fetch(base + '/web/session/authenticate', {method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({jsonrpc:'2.0',id:1,params:{db:'packaging_poc',login:f.issuer.login,password:f.issuer.password}})});
assert.equal((await auth.json()).result.uid, f.issuer.uid);
const session = auth.headers.getSetCookie().map(c => c.split(';')[0]).filter(c => c.startsWith('session_id=')).at(-1)!;
const transport: typeof fetch = async (url, init) => {
  const headers = new Headers(init?.headers);
  headers.set('Cookie', session);
  return fetch(url, {...init, headers});
};
const dms = new OdooDocumentService(base, transport);
const results: {name:string;result:string}[] = [];
const pass = (name:string) => results.push({name, result:'PASS'});
assert.equal(dms.fixture, true);
assert.deepEqual(await dms.template('synthetic-cad-contract','1'),{id:'synthetic-cad-contract',version:'1'}); pass('typed_template');
assert.deepEqual(await dms.generate(j.context,j.input),j.version); pass('generate_replay_exact');
await assert.rejects(dms.generate(j.context,{...j.input,snapshot:{...j.input.snapshot,totalCents:999}}),/operation_conflict/); pass('generate_changed_input_rejected');
assert.deepEqual(await dms.versions(j.context),[j.version]); pass('one_main_document_version');
assert.deepEqual(await dms.signRequest(j.signContext,j.signInput),j.request); pass('sign_request_replay_exact');
await assert.rejects(dms.signRequest(j.signContext,{...j.signInput,signers:[...j.signInput.signers].reverse()}),/operation_conflict/); pass('sign_request_changed_input_rejected');
await assert.rejects(dms.signRequest({...j.signContext,operationId:j.context.operationId},j.signInput),/operation_conflict/); pass('operation_id_reuse_across_methods_rejected');
const pending = await dms.update(j.context,{versionId:j.version.versionId,requestId:j.request.requestId});
assert.equal(pending.status,'pending'); pass('no_signatures_pending');
assert.equal((await dms.artifacts(j.context,j.version.versionId)).length,1); pass('pending_has_no_signed_evidence');
await assert.rejects(dms.update(j.context,{versionId:j.version.versionId,requestId:'999999'}),/request_association_mismatch/); pass('false_completion_association_rejected');
const uploadCtx = {...j.context,documentId:'synthetic-upload-001',operationId:'upload-001'};
const uploadInput = {filename:'synthetic.txt',contentType:'text/plain',contentBase64:Buffer.from('SYNTHETIC upload demonstration').toString('base64')};
const uploaded = await dms.upload(uploadCtx,uploadInput);
assert.deepEqual(await dms.upload(uploadCtx,uploadInput),uploaded); pass('upload_and_replay');
assert.deepEqual(await dms.versions(uploadCtx),[uploaded]); pass('upload_versions');
const artifact = (await dms.artifacts(uploadCtx,uploaded.versionId))[0];
assert.equal(await (await transport(artifact.url)).text(),'SYNTHETIC upload demonstration'); pass('upload_exact_bytes');
await fs.writeFile('artifacts/adapter-tests.json',JSON.stringify({tests:results},null,2));
console.log(JSON.stringify({tests:results},null,2));
